// Regenerates src/api/endpoints.ts from the live Provider API model list.
//
// WHY
// `GET /provider/v1/models` is public — no auth — and each entry carries
// `supported_endpoints`. The server serves THREE route sets, not two:
//
//   ['/chat/completions', '/responses']  67 models
//   ['/messages']                       10 models
//   ['/chat/completions']                9 models   ← not served by /responses
//
// Routing on "Claude ⇒ messages, else responses" sends those 9 to /responses
// and the server answers: Model "…" is not available on this endpoint. Call it
// on /provider/v1/chat/completions instead. So the table is transcribed from the
// server rather than inferred from the prose.
//
// Usage:
//   node scripts/sync-endpoints.mjs            # report only, no writes
//   node scripts/sync-endpoints.mjs --write
import { readFileSync, writeFileSync } from 'node:fs';

const MODELS_URL = 'https://api.commandcode.ai/provider/v1/models';
const TARGET = new URL('../src/api/endpoints.ts', import.meta.url);
const args = new Set(process.argv.slice(2));
const shouldWrite = args.has('--write');

const response = await fetch(MODELS_URL);
if (!response.ok) {
  console.error(`${MODELS_URL} → HTTP ${response.status}`);
  process.exit(1);
}
const payload = await response.json();
const data = payload?.data;
if (!Array.isArray(data) || data.length === 0) {
  console.error('Model list came back empty or in an unexpected shape; not writing.');
  process.exit(1);
}

// Cross-check against the shipped catalog, so a model we serve but the server
// does not know about is reported rather than silently falling back.
const catalogSrc = readFileSync(new URL('../src/catalog.ts', import.meta.url), 'utf8');
const ours = [...catalogSrc.matchAll(/^\s*id: '([^']+)',/gm)].map((m) => m[1]);
const byId = new Map(data.map((m) => [m.id, m]));

const unknown = ours.filter((id) => !byId.has(id));
if (unknown.length > 0) {
  console.error(`\nIn our catalog but not in the API model list (${unknown.length}):`);
  for (const id of unknown) console.error(`  ${id}`);
  console.error('These would fall back to /responses. Check before writing.\n');
}

const q = (s) => `'${String(s).replace(/'/g, "\\'")}'`;
const rows = ours
  .filter((id) => byId.has(id))
  .map((id) => `  { id: ${q(id)}, endpoints: [${byId.get(id).supported_endpoints.map(q).join(', ')}] },`);

const shapes = new Map();
for (const m of data) {
  const k = m.supported_endpoints.join(',');
  shapes.set(k, (shapes.get(k) ?? 0) + 1);
}
console.error(`Fetched ${data.length} models. Route sets across the whole API:`);
for (const [k, v] of [...shapes].sort((a, b) => b[1] - a[1])) {
  console.error(`  ${k.padEnd(34)} ${v}`);
}
console.error(`\nWriting ${rows.length} rows for our catalog.`);

if (!shouldWrite) {
  console.error('Dry run. Pass --write to rewrite src/api/endpoints.ts.');
  process.exit(0);
}

const header = `/**
 * Per-model endpoint routing for the Command Code Provider API.
 *
 * GENERATED by \`node scripts/sync-endpoints.mjs\`. Do not hand-edit.
 *
 * The API serves three different route sets, not the two the prose suggests:
 *
 *   ['/chat/completions', '/responses']  67 models — the normal case
 *   ['/messages']                       10 models — Claude
 *   ['/chat/completions']                9 models — NOT served by /responses
 *
 * That third group is the reason this file exists. Routing on "Claude ⇒
 * messages, else responses" sends the 9 chat-completions-only models to
 * \`/responses\`, and the server answers:
 *
 *   Model "stealth/space-bunny-alpha" is not available on this endpoint.
 *   Call it on /provider/v1/chat/completions instead.
 *
 * \`GET /provider/v1/models\` is public — no auth — and returns
 * \`supported_endpoints\` per model, so this table is transcribed from the server
 * rather than guessed. Re-run the script to refresh it.
 */`;

const file = `${header}

/** The three routes the API exposes, in the form the model list reports them. */
export type ApiRoute = '/chat/completions' | '/responses' | '/messages';

/** One model's declared routes. An empty list means the server said nothing. */
interface EndpointEntry {
  readonly id: string;
  readonly endpoints: readonly ApiRoute[];
}

const ENDPOINTS: readonly EndpointEntry[] = [
${rows.join('\n')}
];

/** id → declared routes, for O(1) lookup on the request path. */
const BY_ID: ReadonlyMap<string, readonly ApiRoute[]> = new Map(
  ENDPOINTS.map((entry) => [entry.id, entry.endpoints]),
);

/** Ids the server did not declare routes for — logged once at activation. */
export function modelsWithoutDeclaredEndpoints(modelIds: readonly string[]): string[] {
  return modelIds.filter((id) => !BY_ID.has(id));
}

/**
 * The route to call for a model.
 *
 * Preference order is deliberate and matches the server's own advice:
 *  1. \`/responses\` when declared — it is the richer dialect and the one the
 *     tool-calling design targets.
 *  2. \`/chat/completions\` when that is all the model serves. Nine models are
 *     chat-completions-only, and sending one to \`/responses\` is a 400.
 *  3. \`/messages\` for a model that serves only that.
 *  4. A model the server said nothing about falls back to the documented
 *     default rather than a guess that will 400.
 */
export function routeFor(modelId: string): ApiRoute {
  const declared = BY_ID.get(modelId);
  if (declared !== undefined && declared.length > 0) {
    if (declared.includes('/responses')) {
      return '/responses';
    }
    if (declared.includes('/chat/completions')) {
      return '/chat/completions';
    }
    if (declared.includes('/messages')) {
      return '/messages';
    }
  }
  return '/responses';
}

/** The declared routes for a model, for diagnostics and tests. */
export function endpointsFor(modelId: string): readonly ApiRoute[] {
  return BY_ID.get(modelId) ?? [];
}
`;

writeFileSync(TARGET, file);
console.error('\nRewrote src/api/endpoints.ts.');
